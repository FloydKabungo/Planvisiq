import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {indexedDB} from 'fake-indexeddb';
import {readFileSync} from 'node:fs';
import {loadWorkspace} from '../js/storage.js';

const dom=new JSDOM(readFileSync(new URL('../workspace.html',import.meta.url),'utf8'),{url:'https://planvisiq.test/workspace.html#slides'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,indexedDB,FormData:dom.window.FormData,FileReader:dom.window.FileReader});
dom.window.scrollTo=()=>{};dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};dom.window.HTMLDialogElement.prototype.close=function(){this.open=false;};
const $=s=>document.querySelector(s),all=s=>[...document.querySelectorAll(s)];
const wait=()=>new Promise(r=>setTimeout(r,80));
const click=async selector=>{assert.ok($(selector),selector);$(selector).click();await wait();};
const set=(selector,value,type='input')=>{assert.ok($(selector),selector);$(selector).value=value;$(selector).dispatchEvent(new dom.window.Event(type,{bubbles:true}));};
await import('../js/app.js');await wait();
test('a ready-made deck can be edited, saved, arranged, presented and kept as separate versions',async()=>{
 assert.match($('#main').textContent,/Your project. Ready for the room/);
 await click('[data-slide-action="create"][data-kind="progress"]');
 assert.equal(all('.slide-rail li').length,7);assert.match($('#slide-canvas').textContent,/Cape Town/);
 set('[data-slide-field="title"]','Stakeholder <review> & progress');
 set('[data-slide-field="notes"]','Talk through the completed work first.');
 set('[data-deck-field="theme"]','navy','change');
 assert.match($('#slide-canvas').textContent,/Stakeholder <review>/);assert.equal($('#slide-canvas review'),null);
 await click('[data-slide-action="add"]');assert.equal(all('.slide-layout-grid button').length,8);
 await click('[data-slide-action="insert"][data-layout="columns"]');
 set('[data-slide-field="leftBody"]','Owner: planning team\nNext review: Friday');
 await click('[data-slide-action="duplicate"]');assert.equal(all('.slide-rail li').length,9);
 await click('[data-slide-action="up"]');assert.match($('.slide-stage-top').textContent,/SLIDE 2/);
 await click('[data-slide-action="delete-slide"]');assert.equal(all('.slide-rail li').length,8);
 await click('[data-slide-action="undo"]');assert.equal(all('.slide-rail li').length,9);
 await click('[data-slide-action="redo"]');assert.equal(all('.slide-rail li').length,8);
 await click('[data-slide-action="present"]');assert.ok($('#slide-presenter').open);
 document.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'End',bubbles:true}));assert.match($('.presenter-controls').textContent,/8 \/ 8/);
 document.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Home',bubbles:true}));assert.match($('.presenter-canvas').textContent,/Stakeholder/);
 document.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));assert.equal($('#slide-presenter'),null);
 await click('[data-slide-action="refresh"]');await click('#dialog [data-slide-action="create"]');
 assert.equal(all('.slide-rail li').length,7);assert.doesNotMatch($('#slide-canvas').textContent,/Stakeholder <review>/);
 await click('[data-slide-action="back"]');assert.equal(all('.deck-card').length,2);
 const saved=await loadWorkspace();assert.equal(saved.projects[0].presentations.length,2);
 const edited=saved.projects[0].presentations.find(d=>d.slides[0].title.startsWith('Stakeholder'));assert.equal(edited.theme,'navy');assert.equal(edited.slides[0].notes,'Talk through the completed work first.');assert.equal(edited.slides.length,8);
 await click('.deck-card [data-slide-action="delete-deck"]');await click('[data-slide-action="cancel"]');assert.equal(all('.deck-card').length,2);
 await click('.deck-card [data-slide-action="delete-deck"]');await click('[data-slide-action="confirm-delete"]');assert.equal(all('.deck-card').length,1);
});
